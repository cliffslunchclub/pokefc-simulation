'use strict';
const assert=require('node:assert/strict');
const p=require('../scripts/phase10-competition-periods.cjs');
const goal=(minute,side)=>({type:'goal',minute,side});
const draws={competition:'league',events:[goal(31,0),goal(83,1)],score:[1,1]};
const leagueWin={competition:'league',events:[goal(31,0)],score:[1,0]};
const knockoutRegulation={competition:'knockout',events:[goal(29,0),goal(84,0),goal(88,1)],score:[2,1]};
const knockoutExtra={competition:'knockout',events:[goal(32,0),goal(87,1),goal(113,0)],score:[2,1]};
const knockoutShootout={competition:'knockout',events:[goal(32,0),goal(87,1),goal(113,0),goal(117,1)],score:[2,2]};
for(const o of [draws,leagueWin,knockoutRegulation,knockoutExtra,knockoutShootout])p.validate(o);
assert.deepEqual(p.periods(draws).map(x=>x.end),[45,90]);
assert.deepEqual(p.periods(leagueWin).map(x=>x.end),[45,90]);
assert.deepEqual(p.periods(knockoutRegulation).map(x=>x.end),[45,90]);
assert.deepEqual(p.periods(knockoutExtra).map(x=>x.end),[45,90,105,120]);
assert.deepEqual(p.periods(knockoutShootout).map(x=>x.end),[45,90,105,120]);
assert.deepEqual(p.stateAt(draws,120).score,[1,1]);
assert.equal(p.stateAt(draws,120).minute,90,'League match cannot extend play');
assert.equal(p.stateAt(draws,90).phase,'full-time');
assert.equal(p.stateAt(draws,90).winnerSide,null);
assert.equal(p.stateAt(leagueWin,90).winnerSide,0);
assert.equal(p.stateAt(knockoutRegulation,90).winnerSide,0);
assert.equal(p.stateAt(knockoutRegulation,120).minute,90);
assert.equal(p.stateAt(knockoutExtra,90).phase,'extra-time-first-half');
assert.equal(p.stateAt(knockoutExtra,104.999).phase,'extra-time-first-half');
assert.equal(p.stateAt(knockoutExtra,105).phase,'extra-time-second-half');
assert.equal(p.stateAt(knockoutExtra,119.999).phase,'extra-time-second-half');
assert.equal(p.stateAt(knockoutExtra,120).phase,'full-time');
assert.deepEqual(p.stateAt(knockoutExtra,90).score,[1,1]);
assert.deepEqual(p.stateAt(knockoutExtra,105).score,[1,1]);
assert.deepEqual(p.stateAt(knockoutExtra,114).score,[2,1]);
assert.equal(p.stateAt(knockoutExtra,120).winnerSide,0);
assert.equal(p.stateAt(knockoutExtra,105).winnerSide,null,'105-minute lead does not end match');
assert.deepEqual(p.stateAt(knockoutShootout,120).score,[2,2]);
assert.equal(p.stateAt(knockoutShootout,120).phase,'penalties-pending');
assert.equal(p.stateAt(knockoutShootout,120).shootoutRequired,true);
assert.equal(p.stateAt(knockoutShootout,120).winnerSide,null);
const a=JSON.stringify(knockoutExtra);
for(const m of [120,0,105,32,87,90,113,120]){
 const first=p.stateAt(knockoutExtra,m);
 const second=p.stateAt(knockoutExtra,m);
 assert.deepEqual(first,second,'Playback must be deterministic');
}
assert.equal(JSON.stringify(knockoutExtra),a,'Original match changed');
assert.throws(()=>p.validate({...draws,events:[goal(91,0)]}),/League match has extra-time goal|Goal ledger/);
assert.throws(()=>p.validate({competition:'knockout',events:[goal(5,1)],score:[0,0]}),/Goal ledger/);
assert.throws(()=>p.validate({competition:'knockout',events:[goal(20,0),goal(91,0)],score:[2,0]}),/Extra-time goal in regulation-only/);
assert.throws(()=>p.stateAt(knockoutExtra,-1),/Invalid playback minute/);
console.log('PASS Phase 10B: league draw, regulation knockout win, 90-to-105-to-120, ET winner, PK handoff, replay/skip parity');
