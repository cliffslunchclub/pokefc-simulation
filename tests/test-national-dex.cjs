'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const ctx=vm.createContext({window:{}});
vm.runInContext(fs.readFileSync(path.join(root,'assets/js/national-species.js'),'utf8'),ctx,{timeout:20000});
const species=ctx.window.FXI_SPECIES;
assert.equal(species.length,1025,'All nine generations should total 1,025 default species');
assert.equal(new Set(species.map(x=>x.id)).size,1025,'All National Dex IDs unique');
const counts=[151,100,135,107,156,72,88,96,120];
for(let g=1;g<=9;g++)assert.equal(species.filter(x=>x.gen===g).length,counts[g-1],'Gen '+g+' count');
for(let id=1;id<=1025;id++){
 const p=species[id-1];
 assert.equal(p.id,id,'Missing or reordered species #'+id);
 assert(p.name&&p.slug&&p.gen,'Missing metadata #'+id);
 assert(p.height>0&&p.weight>0,'Missing physical measurements #'+id);
 assert(Array.isArray(p.types)&&p.types.length>0,'Missing types #'+id);
 assert.equal(p.spriteId,id,'Default numbered sprite unavailable in catalog #'+id);
 for(const k of ['hp','attack','defense','spAttack','spDefense','speed'])assert(Number.isFinite(p.baseStats[k]),'Missing stat '+k+' #'+id);
}
const name=id=>species[id-1].name;
assert.equal(name(233),'Porygon2');
assert.equal(name(493),'Arceus');
assert.equal(name(494),'Victini');
assert.equal(name(658),'Greninja');
assert.equal(name(1000),'Gholdengo');
assert.equal(name(1025),'Pecharunt');
assert(species[792].ultraBeast&&species[792].legendary,'Ultra Beasts count toward challenge legend limit');
assert(species[493].mythical,'Victini is mythical');
const base=vm.createContext({window:{}});
vm.runInContext(fs.readFileSync(path.join(root,'assets/js/species.js'),'utf8'),base);
assert.equal(base.window.FXI_SPECIES.length,493,'32-gym Franchise keeps proven Gen I-IV roster');
const page=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(page.includes('assets/js/national-species.js')&&page.includes('1,025'));
const challenge=fs.readFileSync(path.join(root,'challenge/index.html'),'utf8');
assert(challenge.includes('assets/js/national-species.js'));
assert(challenge.includes('NATIONAL · Gen I–IX (1,025)'));
console.log('PASS complete National Pokédex: 1025/1025, canonical base stats, metadata, sprite IDs, all generations, standalone Franchise legacy catalog');
