'use strict';
const assert=require('node:assert/strict'),path=require('node:path');
const enginePath=path.resolve(__dirname,'../engines/tacticmesh');
for(const f of ['core','analysis','world','tactics','intelligence','physics','rules','telemetry','product-data','engine-facade'])require(path.join(enginePath,'src',f+'.js'));
const TF=globalThis.TF;
Object.assign(TF,{VERSION:require(path.join(enginePath,'tools/version.cjs')),ENGINE_BUILD:require(path.join(enginePath,'tools/engine-version.cjs')).engineBuild});
const boundary=require('./match-handoff.cjs');
const pack=TF.productData.compilePack(TF.productData.starterPack());assert.ok(pack.ok);
const [home,away]=pack.teams;
const config={matchId:'pokefc-handoff-smoke',seed:481205,home,away,halfSeconds:2700};
const original=TF.engine.createMatch(config);
TF.engine.stepMatch(original,200);
const payload=boundary.prepareHandoff(TF.engine,original);
assert.equal(boundary.verifyHandoff(payload,TF.engine),true);
const restored=boundary.restoreWatched(TF.engine,payload);
assert.deepEqual(TF.captureCheckpoint(original.match),TF.captureCheckpoint(restored.match));
TF.engine.stepMatch(original,400);TF.engine.stepMatch(restored,400);
assert.deepEqual(TF.captureCheckpoint(original.match),TF.captureCheckpoint(restored.match),'watched continuation must be deterministic');
const modified=JSON.parse(JSON.stringify(payload));modified.checkpoint.core.score.home+=1;
assert.throws(()=>boundary.verifyHandoff(modified,TF.engine),/integrity/);
assert.throws(()=>boundary.requireQuickSimAdapter(null),/not implemented/);
console.log(JSON.stringify({ok:true,checkpointHash:payload.checkpointHash,engineBuild:payload.engineBuild,tick:payload.at.tick,quickSimConnected:false},null,2));
