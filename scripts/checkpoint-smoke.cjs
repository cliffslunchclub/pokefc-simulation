'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const engine = path.resolve(__dirname, '../engines/tacticmesh');
for (const f of ['core','analysis','world','tactics','intelligence','physics','rules','telemetry','product-data','engine-facade']) require(path.join(engine, 'src', f+'.js'));
const TF = globalThis.TF;
Object.assign(TF, {VERSION: require(path.join(engine,'tools/version.cjs')), ENGINE_BUILD:require(path.join(engine,'tools/engine-version.cjs')).engineBuild});
const compiled = TF.productData.compilePack(TF.productData.starterPack());
assert.equal(compiled.ok, true, 'starter pack compiles');
const [home, away] = compiled.teams;
const config={matchId:'pokefc-checkpoint-smoke',seed:847291,home,away,halfSeconds:2700};
const uninterrupted=TF.engine.createMatch(config);
TF.engine.stepMatch(uninterrupted, 200);
const checkpoint=TF.engine.saveCheckpoint(uninterrupted);
const resumed=TF.engine.restoreCheckpoint(checkpoint);
assert.deepEqual(TF.captureCheckpoint(resumed.match), TF.captureCheckpoint(uninterrupted.match),'checkpoint state equal immediately after restore');
TF.engine.stepMatch(uninterrupted, 400);
TF.engine.stepMatch(resumed, 400);
assert.deepEqual(TF.captureCheckpoint(resumed.match), TF.captureCheckpoint(uninterrupted.match),'checkpoint suffix deterministic');
const replay=TF.engine.createMatch(config);
TF.engine.stepMatch(replay,600);
assert.deepEqual(TF.captureCheckpoint(uninterrupted.match), TF.captureCheckpoint(replay.match),'fresh seed replay deterministic');
console.log(JSON.stringify({ok:true,engineBuild:TF.ENGINE_BUILD,seed:config.seed,tick:600,hash:TF.hashCheckpoint(TF.captureCheckpoint(uninterrupted.match)),eventCount:uninterrupted.match.events.length},null,2));
