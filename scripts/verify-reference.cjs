'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const filename=process.argv[2];
if(!filename) throw Error('Usage: node scripts/verify-reference.cjs reference.json [seed]');
const r=JSON.parse(fs.readFileSync(filename,'utf8'));
const expectSeed=process.argv[3]==null?null:Number(process.argv[3]);
assert.equal(r.kind,'batch-simulation');
assert.equal(r.halfSeconds,2700,'must use 45-minute halves');
assert.equal(r.fullRegulation,true);
assert.equal(r.completedMatches,1);
assert.equal(r.matchesData.length,1);
const m=r.matchesData[0];
if(expectSeed != null) assert.equal(m.seed,expectSeed,'seed should match matrix');
assert.equal(m.finished,true,'match must have completed');
assert.equal(m.shortenedForTesting,false);
assert.ok(m.simulatedSeconds >=5399, 'full 90 minutes must elapse');
for(const k of ['goals','shots','passAttempts','completedPasses','finalTick','runtimeMs'])assert.ok(Number.isFinite(m[k]) && m[k]>=0,`invalid ${k}`);
for(const team of Object.values(m.teams)) for(const key of ['passAttempt','passComplete','shot','tackle','interception']) assert.ok(Number.isFinite(team.counters[key]),`missing ${key}`);
console.log(`PASS seed=${m.seed} score=${m.scoreline} seconds=${m.simulatedSeconds.toFixed(1)} passes=${m.passAttempts} shots=${m.shots} elapsed=${m.runtimeMs.toFixed(0)}ms`);
